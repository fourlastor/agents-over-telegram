#!/usr/bin/env python3
"""Export locked pip requirements at development time; users do not need uv."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib


EXPORTS = {
    "runtime": ["--no-dev", "--no-default-groups", "--no-emit-project"],
    "build": ["--only-group", "bootstrap-build", "--no-default-groups", "--no-emit-project"],
}


def header(root: Path) -> bytes:
    lines = ["# Generated by scripts/export_requirements.py; do not edit."]
    for name in ("uv.lock", "pyproject.toml"):
        lines.append(f"# {name}-sha256: {hashlib.sha256((root / name).read_bytes()).hexdigest()}")
    return ("\n".join(lines) + "\n").encode()


def export_content(root: Path, kind: str, uv: str) -> bytes:
    # Frozen/offline export cannot resolve newer packages or change uv.lock.
    with tempfile.TemporaryDirectory(prefix="aot-requirements-") as cache:
        command = [uv, "--no-config", "--cache-dir", cache, "export", "--frozen", "--offline",
                   "--format", "requirements.txt", "--no-header", "--no-annotate",
                   "--python", sys.executable, "--no-managed-python", "--no-python-downloads", *EXPORTS[kind]]
        result = subprocess.run(command, cwd=root, capture_output=True, timeout=60)
    if result.returncode:
        raise ValueError("Cannot export requirements; check uv and run uv lock before exporting.")
    return header(root) + result.stdout


def _dependency_names(packages: dict, initial: list[dict]) -> set[str]:
    pending = list(initial)
    visited = set()
    names = set()
    while pending:
        dependency = pending.pop()
        name = dependency["name"]
        extras = tuple(dependency.get("extra", []))
        if (name, extras) in visited:
            continue
        visited.add((name, extras))
        names.add(name)
        package = packages[name]
        pending.extend(package.get("dependencies", []))
        for extra in extras:
            pending.extend(package.get("optional-dependencies", {}).get(extra, []))
    return names


def validate_exports(root: Path) -> None:
    """Check packaged pins, hashes and source digests without running uv or networking."""
    project = tomllib.loads((root / "pyproject.toml").read_text())
    lock = tomllib.loads((root / "uv.lock").read_text())
    packages = {package["name"]: package for package in lock["package"]}
    if len(packages) != len(lock["package"]):
        raise ValueError("Requirements validation needs distinct locked package names")
    package = packages[project["project"]["name"]]
    if package["version"] != project["project"]["version"]:
        raise ValueError("Project version and dependency lock differ")
    if project["build-system"]["requires"] != project["dependency-groups"]["bootstrap-build"]:
        raise ValueError("Bootstrap build group must match the project build requirements")
    initial = {
        "runtime": package["dependencies"],
        "build": package["dev-dependencies"]["bootstrap-build"],
    }
    expected_header = header(root)
    for kind in EXPORTS:
        path = root / "requirements" / f"{kind}.txt"
        if path.is_symlink() or path.parent.is_symlink() or not path.is_file():
            raise ValueError(f"Packaged {kind} requirements are missing or unsafe")
        contents = path.read_bytes()
        if not contents.startswith(expected_header):
            raise ValueError(f"Packaged {kind} requirements are stale; run scripts/export_requirements.py")
        names = set()
        for line in contents.decode().replace("\\\n", "").splitlines():
            if not line.strip() or line.startswith("#"):
                continue
            fields = line.split("--hash=")
            pin = re.fullmatch(r"([a-z0-9][a-z0-9._-]*)==([A-Za-z0-9.+!-]+)(?:\s*;\s*[^#]+)?", fields[0].strip())
            hashes = [field.strip() for field in fields[1:]]
            if pin is None or "--" in fields[0] or "://" in fields[0] or not hashes or any(not re.fullmatch(r"sha256:[0-9a-f]{64}", value) for value in hashes):
                raise ValueError(f"Packaged {kind} requirements must contain only exact pins and SHA256 hashes")
            name, version = pin.groups()
            locked = packages.get(name)
            if locked is None or locked["version"] != version or name in names:
                raise ValueError(f"Packaged {kind} requirements differ from locked versions")
            artifacts = [*locked.get("wheels", []), *([locked["sdist"]] if "sdist" in locked else [])]
            if set(hashes) != {artifact["hash"] for artifact in artifacts}:
                raise ValueError(f"Packaged {kind} requirement hashes differ from the lock")
            names.add(name)
        if names != _dependency_names(packages, initial[kind]):
            raise ValueError(f"Packaged {kind} requirements omit or add locked dependencies")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed exports exactly match uv's output")
    parser.add_argument("--uv", default="uv", help="Development uv executable (never needed by runtime bootstrap)")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    uv = shutil.which(args.uv)
    if uv is None:
        parser.error("uv is needed only to generate/check development exports, not to install the plugin")
    try:
        outputs = {kind: export_content(root, kind, uv) for kind in EXPORTS}
        for kind, contents in outputs.items():
            path = root / "requirements" / f"{kind}.txt"
            if args.check:
                if not path.is_file() or path.read_bytes() != contents:
                    raise ValueError(f"requirements/{kind}.txt is stale; run scripts/export_requirements.py")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(contents)
        validate_exports(root)
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        parser.error(str(error))
    print("Locked pip requirements checked." if args.check else "Locked pip requirements exported.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
